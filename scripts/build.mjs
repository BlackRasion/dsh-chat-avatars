#!/usr/bin/env node
/**
 * 零依赖拼接构建：src/NN-name.js（按数字前缀排序）→ client.js。
 *
 * 为什么是拼接而不是打包器：
 * - dsh 的客户端 bundle 必须是一个 classic script，经 window.__ModuleLoader__.load 注册；
 *   手写插件不支持同步相对 require，打包器只能解决“源码组织”而不是加载契约。
 * - 用 Node 内置 API 做确定性拼接，零第三方依赖、零安装步骤，源码可读性与产物契约兼得。
 *
 * 用法：
 *   node scripts/build.mjs           写入 client.js
 *   node scripts/build.mjs --check   只校验 client.js 是否与 src/ 同步（CI 用）
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SRC_DIR = path.join(ROOT, 'src');
const OUT_FILE = path.join(ROOT, 'client.js');
const MODULE_FILE = /^\d{2}-[a-z0-9-]+\.js$/;
const packageJson = JSON.parse(readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const checkOnly = process.argv.includes('--check');

function fail(message) {
  console.error('build: ' + message);
  process.exit(1);
}

const files = readdirSync(SRC_DIR)
  .filter((name) => MODULE_FILE.test(name))
  .sort();

if (files.length === 0) fail('src/ 下没有 NN-name.js 模块');

const prefixes = new Set();
for (const name of files) {
  const prefix = name.slice(0, 2);
  if (prefixes.has(prefix)) fail('重复的模块前缀 "' + prefix + '"（' + name + '）');
  prefixes.add(prefix);
}

const moduleText = files
  .map((name) => {
    const body = readFileSync(path.join(SRC_DIR, name), 'utf8').trimEnd();
    const rule = '─'.repeat(Math.max(8, 74 - name.length));
    return '// ── src/' + name + ' ' + rule + '\n' + body;
  })
  .join('\n\n');

const contractMatch = /const PACKAGE_NAME = '([^']+)';/.exec(moduleText);
if (!contractMatch) fail("src/10-contract.js 必须声明 const PACKAGE_NAME = '<包名>';");
if (contractMatch[1] !== packageJson.name) {
  fail('PACKAGE_NAME "' + contractMatch[1] + '" 与 package.json name "' + packageJson.name + '" 不一致');
}

const banner = [
  '// @generated by scripts/build.mjs — do not edit by hand.',
  '// Source of truth: src/NN-*.js (concatenated in numeric order).',
  '// Regenerate: npm run build     Verify: npm run check-build',
  '// Bundle: ' + packageJson.name + '@' + packageJson.version,
  '// Modules: ' + files.join(', ')
].join('\n');

const generated = [
  banner,
  '',
  'window.__ModuleLoader__.load({',
  '  id: ' + JSON.stringify(packageJson.name) + ',',
  '  factory(require) {',
  "    'use strict';",
  '    try {',
  "      const React = require('react');",
  '      const h = React.createElement;',
  '',
  moduleText,
  '',
  '      // 插件面：最小 inject；apply 由 src/90-apply.js 提供。',
  '      return {',
  "        inject: ['slots'],",
  "        apply: typeof apply === 'function' ? apply : function applyNoop() {}",
  '      };',
  '    } catch (error) {',
  '      // 启动安全：factory 永不向宿主抛错（抛错会导致整站 "Failed to load plugins"）。',
  '      try {',
  "        console.warn('[" + packageJson.name + "] degraded: ' + (error && error.message ? error.message : String(error)));",
  '      } catch (ignored) {}',
  "      return { inject: [], apply: function applyDegraded() {} };",
  '    }',
  '  }',
  '});',
  ''
].join('\n');

if (checkOnly) {
  if (!existsSync(OUT_FILE)) fail('client.js 不存在，请先运行 npm run build');
  const current = readFileSync(OUT_FILE, 'utf8');
  if (current !== generated) {
    const expected = generated.split('\n');
    const actual = current.split('\n');
    const length = Math.max(expected.length, actual.length);
    for (let index = 0; index < length; index += 1) {
      if (expected[index] !== actual[index]) {
        fail('client.js 与 src/ 不同步（首个差异在第 ' + String(index + 1) + ' 行），请运行 npm run build');
      }
    }
    fail('client.js 与 src/ 不同步，请运行 npm run build');
  }
  console.log('build: client.js 已是最新（' + files.length + ' 个模块）');
  process.exit(0);
}

writeFileSync(OUT_FILE, generated);
console.log('build: 写入 client.js（' + files.length + ' 个模块，' + String(Buffer.byteLength(generated)) + ' 字节）');
