import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';

const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const patch = readFileSync(new URL('../cordis.patch.yml', import.meta.url), 'utf8');
const client = readFileSync(new URL('../client.js', import.meta.url), 'utf8');

test('包名与 dsh 加载契约字段', () => {
  assert.match(pkg.name, /^[a-z0-9][a-z0-9._-]*$/);
  assert.equal(pkg.exports['./client'], './client.js');
  assert.equal(pkg.dsh.bundle.patch, './cordis.patch.yml');
  assert.equal(pkg.dsh.client.platform, 'web');
  assert.ok(pkg.engines.dsh, '必须声明 engines.dsh（安装期兼容门禁）');
  assert.ok(pkg.files.includes('client.js'), '发布物必须包含生成的 client.js');
  assert.ok(pkg.files.includes('icon.webp'), '发布物必须包含插件图标');
  assert.equal(pkg.exports['./icon'], './icon.webp');
  for (const internal of ['docs/', 'src/', 'scripts/', 'test/']) {
    assert.ok(!pkg.files.includes(internal), `files 不应包含内部目录 ${internal}`);
  }
});

test('bundle patch 与包名一致', () => {
  assert.match(patch, /- insert:/);
  assert.match(patch, new RegExp("- id: '?dsh-chat-avatars'?"));
  assert.match(patch, new RegExp("name: '?" + pkg.name + "'?"));
});

test('locale meta 可被 Plugin Manager 读取', () => {
  for (const file of ['../locale/en.json', '../locale/zh.json']) {
    const locale = JSON.parse(readFileSync(new URL(file, import.meta.url), 'utf8'));
    assert.equal(typeof locale.meta.title, 'string');
    assert.equal(typeof locale.meta.description, 'string');
  }
});

test('生成物带有正确标识且不含宿主 client 包依赖', () => {
  assert.match(client, /@generated by scripts\/build\.mjs/);
  assert.ok(client.includes(JSON.stringify(pkg.name)));
  assert.doesNotMatch(client, /require\(['"]@deepseek-ai\/dsh-client-/);
});
